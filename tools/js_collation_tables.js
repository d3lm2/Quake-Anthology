// Generates src/foundation/js_collation_tables.inc from the JS engine that runs the TS
// oracle: bun tools/js_collation_tables.js > src/foundation/js_collation_tables.inc
// For every code point of RANGES, its weights under bun's default collator (the one
// String.prototype.localeCompare uses): the dense rank of its class among all of
// them at base, accent and variant sensitivity (0: ignorable at that level), so a
// string compares by its primary sequence, then its secondary, then its tertiary.
// Code points that collate as a sequence at base strength (NFKD forms such as
// "1⁄4" for "¼", and "ae", "oe", "ss", "th" candidates) are expansions: they get
// their parts' weights, tertiary nudged to fall where bun puts the character.
const RANGES = [
  [0x0000, 0x052f], // Basic Latin through Cyrillic Supplement
  [0x1e00, 0x1eff], // Latin Extended Additional
  [0x2000, 0x20cf], // General Punctuation, super/subscripts, currency
  [0x2100, 0x218f], // Letterlike symbols, number forms
  [0x3000, 0x30ff], // CJK symbols and punctuation, Hiragana, Katakana
  [0xff00, 0xffef], // Halfwidth and fullwidth forms
];
const base = new Intl.Collator(undefined, { sensitivity: "base" });
const accent = new Intl.Collator(undefined, { sensitivity: "accent" });
const variant = new Intl.Collator(undefined, { sensitivity: "variant" });
const points = [];
for (const [first, last] of RANGES) for (let c = first; c <= last; c++) points.push(c);
const ranks = collator => {
  const text = new Map(points.map(c => [c, String.fromCodePoint(c)]));
  const live = points.filter(c => collator.compare(text.get(c), "") !== 0);
  live.sort((a, b) => collator.compare(text.get(a), text.get(b)) || a - b);
  const rank = new Map();
  let current = 0;
  for (let i = 0; i < live.length; i++) {
    if (i === 0 || collator.compare(text.get(live[i - 1]), text.get(live[i])) !== 0) current++;
    rank.set(live[i], current);
  }
  return rank;
};
const p = ranks(base), s = ranks(accent), t = ranks(variant);
const weight = c => [p.get(c) ?? 0, 4 * (s.get(c) ?? 0), 4 * (t.get(c) ?? 0)];
const inRanges = c => RANGES.some(([a, b]) => c >= a && c <= b);
const expansions = [];
const candidates = ["ae", "oe", "ss", "th", "AE", "OE", "SS", "TH", "Ae", "Oe", "Ss", "Th"];
for (const c of points) {
  const ch = String.fromCodePoint(c);
  const forms = [ch.normalize("NFKD"), ...candidates].filter(form => {
    const parts = [...form].map(x => x.codePointAt(0));
    return parts.length >= 2 && parts.every(inRanges) && parts.filter(x => (p.get(x) ?? 0) !== 0).length >= 2 &&
      base.compare(ch, form) === 0;
  });
  if (forms.length === 0) continue;
  // Accent-equal forms nudge the tertiary weight, others the secondary; a form in the
  // character's case is preferred; then the form bun ranks equal, else the nearest one
  // below (nudged up), else the nearest above (nudged down).
  let pool = forms.filter(f => accent.compare(f, ch) === 0);
  const level = pool.length > 0 ? 2 : 1;
  if (pool.length === 0) pool = forms;
  const lowerCh = ch === ch.toLowerCase();
  const cased = pool.filter(f => (lowerCh ? f === f.toLowerCase() : f === f.toUpperCase()));
  if (cased.length > 0) pool = cased;
  const cmp = level === 2 ? variant : accent;
  const below = pool.filter(f => cmp.compare(f, ch) < 0).sort(cmp.compare);
  const above = pool.filter(f => cmp.compare(f, ch) > 0).sort(cmp.compare);
  const equal = pool.find(f => cmp.compare(f, ch) === 0);
  const form = equal ?? (below.length > 0 ? below[below.length - 1] : above[0]);
  const order = cmp.compare(ch, form);
  const list = [...form].map(x => weight(x.codePointAt(0))).filter(w => w[0] !== 0 || w[1] !== 0 || w[2] !== 0);
  if (order !== 0 && list.length > 0) list[list.length - 1][level] += order > 0 ? 1 : -1;
  expansions.push([c, list]);
}
const lines = [];
lines.push(`/* Generated by bun tools/js_collation_tables.js (bun ${Bun.version}); do not edit. */`);
lines.push(`static const js_collation_range js_collation_ranges[] = {`);
let offset = 0;
for (const [a, b] of RANGES) { lines.push(`  {0x${a.toString(16)}, 0x${b.toString(16)}, ${offset}},`); offset += b - a + 1; }
lines.push(`};`);
lines.push(`static const js_collation_weight js_collation_weights[] = {`);
for (let i = 0; i < points.length; i += 6)
  lines.push("  " + points.slice(i, i + 6).map(c => `{${weight(c).join(", ")}}`).join(", ") + ",");
lines.push(`};`);
lines.push(`static const js_collation_expansion js_collation_expansions[] = {`);
for (const [c, list] of expansions)
  lines.push(`  {0x${c.toString(16)}, ${list.length}, {${list.map(w => `{${w.join(", ")}}`).join(", ")}}},`);
lines.push(`};`);
lines.push(`#define JS_COLLATION_PRIMARY_LIMIT ${Math.max(...p.values()) + 1}u`);
console.log(lines.join("\n"));
